  const id = params.id as string;

  const [invoice, setInvoice] = useState<Invoice | null>(null);
  const [loading, setLoading] = useState(true);
  const [pdfLoading, setPdfLoading] = useState(false);
  const [editOpen, setEditOpen] = useState(false);
  const [saving, setSaving] = useState(false);
  const [mounted, setMounted] = useState(false);
  const [invoiceLocale, setInvoiceLocale] = useState<Locale>(appLocale);

  const [editDueDate, setEditDueDate] = useState("");
  const [editTax, setEditTax] = useState(0);
  const [editDiscount, setEditDiscount] = useState(0);
  const [editNotes, setEditNotes] = useState("");
  const [editItems, setEditItems] = useState<EditItem[]>([]);

  const invoiceRef = useRef<HTMLDivElement | null>(null);
  function confirmToast(message: string) {
    return new Promise<boolean>((resolve) => {
      let settled = false;

      const toastId = toast(message, {
        duration: 10000,
        action: {
          label: "تأكيد",
          onClick: () => {
            if (settled) return;
            settled = true;
            toast.dismiss(toastId);
            resolve(true);
          },
        },
        onDismiss: () => {
          if (settled) return;
          settled = true;
          resolve(false);
        },
        onAutoClose: () => {
          if (settled) return;
          settled = true;
          resolve(false);
        },
      });
    });
  }

  async function load() {
    if (!id || id === "undefined" || id === "null") {
      setInvoice(null);
      setLoading(false);
      return;
    }

    try {
      setLoading(true);

      const res = await fetch(`/api/invoices/${id}`, {
        cache: "no-store",
      });

      if (res.status === 401) {
        window.location.href = "/login";
        return;
      }

      const data = await res.json().catch(() => ({}));

      if (!res.ok) {
        console.error("Invoice load failed:", {
          id,
          status: res.status,
          data,
        });

        setInvoice(null);
        return;
      }

      setInvoice(data.data?.invoice ?? data.data ?? data.invoice ?? null);
    } catch (error) {
      console.error("Invoice load error:", error);
      setInvoice(null);
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    setMounted(true);
  }, []);

  useEffect(() => {
    setInvoiceLocale(appLocale);
  }, [appLocale]);

  useEffect(() => {
    if (id) load();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id]);

  function openEditModal() {
    if (!invoice) return;

    if (invoice.status === "PAID") {
      toast.error(
        "لا يمكن تعديل البيانات المالية لفاتورة مدفوعة. غيّر الحالة أولًا إذا احتجت تعديلها.",
      );
      return;
    }

    setEditDueDate(toDateInput(invoice.dueDate));
    setEditTax(invoice.tax || 0);
    setEditDiscount(invoice.discount || 0);
    setEditNotes(invoice.notes || "");
    setEditItems(
      invoice.items.map((item) => ({
        description: item.description,
        quantity: item.quantity,
        unitPrice: item.unitPrice,
      })),
    );
    setEditOpen(true);
  }

  function updateEditItem(index: number, key: keyof EditItem, value: string) {
    setEditItems((prev) =>
      prev.map((item, i) =>
        i === index
          ? {
              ...item,
              [key]: key === "description" ? value : Number(value || 0),
            }
          : item,
      ),
    );
  }

  function addEditItem() {
    setEditItems((prev) => [
      ...prev,
      {
        description: "",
        quantity: 1,
        unitPrice: 0,
      },
    ]);
  }

  function removeEditItem(index: number) {
    setEditItems((prev) => prev.filter((_, i) => i !== index));
  }

  const editSubtotal = roundMoney(
    editItems.reduce((sum, item) => {
      const quantity = Number(item.quantity || 0);
      const unitPrice = Number(item.unitPrice || 0);
      return sum + quantity * unitPrice;
    }, 0),
  );

  const editTotal = roundMoney(
    editSubtotal + Number(editTax || 0) - Number(editDiscount || 0),
  );

  async function submitEdit(e: FormEvent) {
    e.preventDefault();
    if (!invoice) return;

    const cleanItems = editItems
      .map((item) => ({
        description: item.description.trim(),
        quantity: Number(item.quantity || 0),
        unitPrice: Number(item.unitPrice || 0),
      }))
      .filter((item) => item.description);

    if (cleanItems.length === 0) {
      toast.error("أضف بند واحد على الأقل");
      return;
    }

    if (cleanItems.some((item) => item.quantity <= 0 || item.unitPrice < 0)) {
      toast.error("تأكد أن الكمية أكبر من صفر وأن سعر الوحدة غير سالب");
      return;
    }

    if (Number(editTax || 0) < 0 || Number(editDiscount || 0) < 0) {
      toast.error("الضريبة والخصم لا يمكن أن تكون قيمهم سالبة");
      return;
    }

    if (editTotal < 0) {
      toast.error("الخصم لا يمكن أن يكون أكبر من المجموع والضريبة");
      return;
    }

    try {
      setSaving(true);

      const res = await fetch(`/api/invoices/${invoice.id}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          dueDate: editDueDate || null,
          tax: Number(editTax || 0),
          discount: Number(editDiscount || 0),
          notes: editNotes,
          items: cleanItems,
        }),
      });

      const data = await res.json().catch(() => ({}));

      if (!res.ok) {
        toast.error(data.message || data.error || "تعذر تعديل الفاتورة");
        return;
      }

      toast.success("تم تعديل الفاتورة");
      setEditOpen(false);
      await load();
    } finally {
      setSaving(false);
    }
  }

  async function updateStatus(nextStatus: InvoiceStatus) {
    if (!invoice || invoice.status === nextStatus) return;

    if (nextStatus === "PAID" && !invoice.case) {
      toast.error(
        "لا يمكن تعليم الفاتورة كمدفوعة لأنها غير مرتبطة بقضية. اربطها بقضية أولًا حتى يتم إنشاء دفعة صحيحة.",
      );
      return;
    }

    if (invoice.payment && invoice.status === "PAID" && nextStatus !== "PAID") {
      const confirmed = await confirmToast(
        "هذه الفاتورة مدفوعة ومرتبطة بدفعة. تغيير الحالة سيحدّث حالة الدفعة المرتبطة حسب الحالة الجديدة. هل تريد المتابعة؟",
      );

      if (!confirmed) return;
    }

    const res = await fetch(`/api/invoices/${invoice.id}`, {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: nextStatus }),
    });

    const data = await res.json().catch(() => ({}));

    if (!res.ok) {
      toast.error(data.message || data.error || "تعذر تحديث حالة الفاتورة");
      return;
    }

    toast.success("تم تحديث حالة الفاتورة");
    await load();
  }

  async function deleteInvoice() {
    if (!invoice) return;

    if (isArchivedInvoice(invoice)) {
      toast.error("لا يمكن حذف فاتورة مرتبطة بموكل مؤرشف");
      return;
    }

    if (invoice.payment) {
      toast.error(
        "لا يمكن حذف هذه الفاتورة لأنها مرتبطة بدفعة. عالج الدفعة المرتبطة أولًا ثم حاول مرة أخرى.",
      );
      return;
    }

    const confirmed = await confirmToast("هل أنت متأكد من حذف هذه الفاتورة؟");
    if (!confirmed) return;

    const res = await fetch(`/api/invoices/${invoice.id}`, {
      method: "DELETE",
    });

    const data = await res.json().catch(() => ({}));

    if (!res.ok) {
      toast.error(data.message || data.error || "تعذر حذف الفاتورة");
      return;
    }

    toast.success("تم حذف الفاتورة");
    router.push("/dashboard/invoices");
  }

  async function sendInvoiceWhatsApp() {
    if (!invoice) return;

    let rawPhone =
      invoice.client?.whatsappNumber ||
      invoice.client?.whatsapp ||
      invoice.client?.phone ||
      invoice.client?.mobile ||
      null;

    if (!rawPhone && invoice.client?.id) {
      try {
        const response = await fetch(`/api/clients/${invoice.client.id}`, {
          cache: "no-store",
        });
        const data = response.ok ? await response.json().catch(() => ({})) : {};

        rawPhone = extractClientPhone(data);
      } catch {
        rawPhone = null;
      }
    }

    const phone = normalizeWhatsAppPhone(rawPhone);

    if (!phone) {
      toast.error(
        invoiceLocale === "ar"
          ? "لا يوجد رقم واتساب أو هاتف محفوظ لهذا الموكل"
          : "No WhatsApp or phone number is saved for this client",
      );
      return;
    }

    window.open(
      `https://wa.me/${phone}?text=${encodeURIComponent(
        buildInvoiceWhatsAppMessage(invoice, invoiceLocale),
      )}`,
      "_blank",
      "noopener,noreferrer",
    );
  }

  async function downloadInvoicePDF() {
    if (!invoiceRef.current || !invoice) return;

    try {
      setPdfLoading(true);

      const html2canvas = (await import("html2canvas")).default;
      const { jsPDF } = await import("jspdf");

      const canvas = await html2canvas(invoiceRef.current, {
        scale: 2,
        useCORS: true,
        backgroundColor: "#ffffff",
      });

      const imgData = canvas.toDataURL("image/png");

      const pdf = new jsPDF({
        orientation: "p",
        unit: "mm",
        format: "a4",
      });

      const pageWidth = pdf.internal.pageSize.getWidth();
      const pageHeight = pdf.internal.pageSize.getHeight();
      const margin = 10;
      const usableWidth = pageWidth - margin * 2;
      const imgWidth = usableWidth;
      const imgHeight = (canvas.height * imgWidth) / canvas.width;

      let heightLeft = imgHeight;
      let position = margin;

      pdf.addImage(imgData, "PNG", margin, position, imgWidth, imgHeight);
      heightLeft -= pageHeight - margin * 2;

      while (heightLeft > 0) {
        position = heightLeft - imgHeight + margin;
        pdf.addPage();
        pdf.addImage(imgData, "PNG", margin, position, imgWidth, imgHeight);
        heightLeft -= pageHeight - margin * 2;
      }

      pdf.save(`${safeInvoiceFilename(invoice.invoiceNumber)}.pdf`);
    } catch (error) {
      console.error(error);
      toast.error("تعذر إنشاء ملف PDF");
    } finally {
      setPdfLoading(false);
    }
  }

