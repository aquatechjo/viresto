function escapeHtml(value: unknown) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function date(value: string | Date | null | undefined, locale: ReceiptLocale) {
  if (!value) return "-";
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) return "-";
  return formatInZone(parsed, locale, { year: "numeric", month: "2-digit", day: "2-digit" });
}

export function amountInWords(amount: number, locale: ReceiptLocale) {
  return locale === "ar" ? amountInArabicWords(amount) : amountInEnglishWords(amount);
}

