export type ReceiptLocale = "ar" | "en";

/** What POST /api/payments/[id]/receipt returns. */
export type PrintableReceipt = {
  id: string;
  /** Null only on a cancelled payment that never had one. */
  receiptNumber: string | null;
  status: "PAID" | "CANCELLED";
  amount: number;
  method: string;
  reference?: string | null;
  paidAt?: string | null;
  cancelledAt?: string | null;
  cancellationReason?: string | null;
  client: { name?: string | null; phone?: string | null };
  case?: { title?: string | null; caseNumber?: string | null } | null;
  invoice?: { invoiceNumber?: string | null } | null;
  /** Unknown (null) for payments collected before 2026-11-08. */
  collectedBy?: { name?: string | null } | null;
  tenant?: {
    name?: string | null;
    email?: string | null;
    phone?: string | null;
    address?: string | null;
    logoUrl?: string | null;
  } | null;
};

