/**
 * Fetches the receipt (which numbers an older collected payment on its
 * first print) and opens it for printing. The window is opened before the
 * request, so the browser does not block it as a pop-up.
 */
export async function printPaymentReceipt(paymentId: string, locale: ReceiptLocale) {
  const copy = COPY[locale];
  const printWindow = window.open("", "_blank", "width=980,height=850");

  if (!printWindow) {
    toast.error(copy.popupBlocked);
    return null;
  }

  try {
    const response = await fetch(`/api/payments/${encodeURIComponent(paymentId)}/receipt`, {
      method: "POST",
      credentials: "same-origin",
    });
    const payload = await response.json().catch(() => null);

    if (!response.ok || !payload?.success) {
      printWindow.close();
      toast.error(payload?.error || payload?.message || (locale === "ar" ? "تعذر تجهيز السند" : "Could not prepare the receipt"));
      return null;
    }

    const receipt = payload.data as PrintableReceipt;
    const logoUrl = receipt.tenant?.logoUrl;
    const printable: PrintableReceipt = {
      ...receipt,
      tenant: receipt.tenant
        ? {
            ...receipt.tenant,
            logoUrl: logoUrl && !/^(https?:|data:|blob:)/i.test(logoUrl)
              ? new URL(logoUrl, window.location.origin).href
              : logoUrl,
          }
        : null,
    };

    printWindow.document.open();
    printWindow.document.write(buildReceiptPrintHtml(printable, locale));
    printWindow.document.close();
    return receipt;
  } catch {
    printWindow.close();
    toast.error(locale === "ar" ? "تعذر تجهيز السند" : "Could not prepare the receipt");
    return null;
  }
}
