export function amountInWords(amount: number, locale: ReceiptLocale) {
  return locale === "ar" ? amountInArabicWords(amount) : amountInEnglishWords(amount);
}

/**
 * Fetches the receipt (which numbers an older collected payment on its
 * first print) and prints it on the shared report system. The window is
 * opened before the request, so the browser does not block it as a pop-up.
 */
export async function printPaymentReceipt(paymentId: string, locale: ReceiptLocale) {
  const copy = RECEIPT_COPY[locale];
  const printWindow = openReportWindow();

  if (!printWindow) {
    toast.error(copy.popupBlocked);
    return null;
  }

  try {
    const response = await fetch(`/api/payments/${encodeURIComponent(paymentId)}/receipt`, {
      method: "POST",
      credentials: "same-origin",
    });
    const payload = await response.json().catch(() => null);

    if (!response.ok || !payload?.success) {
      printWindow.close();
      toast.error(payload?.error || payload?.message || copy.failed);
      return null;
    }

    const receipt = payload.data as PrintableReceipt;
    const [{ buildReceiptPrintHtml }, logoUrl] = await Promise.all([
      import("@/lib/reports/receipt-document"),
      usableLogoUrl(receipt.tenant?.logoUrl),
    ]);
    const html = buildReceiptPrintHtml(receipt, locale, {
      assetBaseUrl: window.location.origin,
      logoUrl,
    });
    await printReportInWindow(printWindow, html);
    return receipt;
  } catch {
    printWindow.close();
    toast.error(copy.failed);
    return null;
  }
}
