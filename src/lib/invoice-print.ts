export function detectInvoiceLocale(locale?: InvoiceLocale): InvoiceLocale {
  if (locale) return locale;

  if (typeof document !== "undefined") {
    const documentLanguage = document.documentElement.lang?.toLowerCase();
    if (documentLanguage?.startsWith("en")) return "en";
  }

  return "ar";
}

/**
 * The number as shown. A draft has none until it is issued (no gaps in
 * issued numbers), so it shows "Draft" in the given language.
 */
export function formatInvoiceNumber(
  invoiceNumber?: string | null,
  locale?: InvoiceLocale,
) {
  if (!invoiceNumber) return INVOICE_COPY[detectInvoiceLocale(locale)].draft;
  return invoiceNumber.startsWith("#") ? invoiceNumber : `#${invoiceNumber}`;
}

export function normalizeWhatsAppPhone(phone?: string | null) {
  if (!phone) return "";

  // wa.me takes the E.164 digits without "+".
  const normalized = normalizePhone(phone);
  if (normalized) return normalized.slice(1);

  const cleaned = phone.replace(/[^\d+]/g, "");

  if (cleaned.startsWith("+")) return cleaned.slice(1);
  if (cleaned.startsWith("00")) return cleaned.slice(2);
  if (cleaned.startsWith("0")) return `962${cleaned.slice(1)}`;

  return cleaned;
}

/** "10/11/2026" in Amman: the short date of the WhatsApp message. */
function shortDate(value: string | Date | null | undefined, locale: InvoiceLocale) {
  if (!value) return "-";

  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) return "-";

  return formatInZone(parsed, locale, {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  });
}

export function invoiceCaseText(invoice: PrintableInvoice, locale: InvoiceLocale) {
  return invoice.case
    ? `${invoice.case.title || "-"}${invoice.case.caseNumber ? ` - ${invoice.case.caseNumber}` : ""}`
    : INVOICE_COPY[locale].noCase;
}

export function buildInvoiceWhatsAppMessage(
  invoice: PrintableInvoice,
  requestedLocale?: InvoiceLocale,
) {
  const locale = detectInvoiceLocale(requestedLocale);
  const copy = INVOICE_COPY[locale];
  const tenantName = invoice.tenant?.name || "Viresto";

  return `${copy.whatsappGreeting} ${invoice.client?.name || ""}

${copy.whatsappIntro}

${copy.invoiceNumber}: ${formatInvoiceNumber(invoice.invoiceNumber, locale)}
${copy.status}: ${invoiceStatusText(invoice.status, invoice.isOverdue, copy.statuses)}
${copy.caseDetails}: ${invoiceCaseText(invoice, locale)}
${copy.issueDate}: ${shortDate(invoice.issueDate, locale)}
${copy.dueDate}: ${shortDate(invoice.dueDate, locale)}
${copy.finalTotal}: ${formatJOD(invoice.total)}

${copy.whatsappReview}

${copy.regards}
${tenantName}`.trim();
}

/**
 * Prints the invoice (or saves it as a PDF from the print dialog), on the
 * shared report system. The window is opened first, from the click, so it
 * is not blocked as a pop-up.
 */
export async function printInvoiceDocument(
  invoice: PrintableInvoice,
  locale?: InvoiceLocale,
) {
  const resolvedLocale = detectInvoiceLocale(locale);
  const copy = INVOICE_COPY[resolvedLocale];
  const printWindow = openReportWindow();

  if (!printWindow) {
    toast.error(copy.printPopupBlocked);
    return;
  }

  try {
    const [{ buildInvoicePrintHtml }, logoUrl] = await Promise.all([
      import("@/lib/reports/invoice-document"),
      usableLogoUrl(invoice.tenant?.logoUrl),
    ]);
    const html = buildInvoicePrintHtml(invoice, resolvedLocale, {
      assetBaseUrl: window.location.origin,
      logoUrl,
    });
    await printReportInWindow(printWindow, html);
  } catch {
    printWindow.close();
    toast.error(copy.printFailed);
  }
}
